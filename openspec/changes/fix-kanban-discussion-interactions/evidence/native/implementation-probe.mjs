import assert from 'node:assert/strict'
import { chromium } from '/home/capz/worktrees/hermes-kanban-detail/node_modules/playwright/index.mjs'
import { writeFile } from 'node:fs/promises'
const root = new URL('.', import.meta.url).pathname
const browser = await chromium.launch({ headless: true, executablePath: '/opt/google/chrome/chrome' })
const page = await browser.newPage({ viewport: { width: 1200, height: 900 } })
const checks = [], errors = [], external = []
const check = (name, value) => { assert(value, name); checks.push(name) }
page.on('pageerror', error => errors.push(error.message))
page.on('request', request => { if (request.url().includes('example.invalid')) external.push(request.url()) })
try {
  await page.goto('http://127.0.0.1:43311/implementation.html', { waitUntil: 'networkidle' })
  await page.locator('[data-comment-id]').first().waitFor()
  await page.screenshot({ path: root + 'implementation-wide.png' })
  const first = page.locator('[data-comment-id="8"]')
  const height = await first.evaluate(element => element.getBoundingClientRect().height)
  await first.getByRole('button', { name: 'Expand', exact: true }).click()
  check('rich body expands to greater visible height', await first.evaluate(element => element.getBoundingClientRect().height) > height)
  await first.getByRole('button', { name: /Select comment/ }).click()
  await first.getByRole('button', { name: 'Collapse', exact: true }).click()
  check('selected context remains selectable while collapsed', await first.getByRole('button', { name: /Select comment/ }).getAttribute('aria-pressed') === 'true')
  check('collapsed links inert', await first.locator('[inert]').count() === 1)
  await page.getByRole('button', { name: 'Discussion floors', exact: true }).click()
  await page.getByRole('textbox', { name: 'Jump to #' }).fill('1')
  await page.locator('.kanban-floor-menu').getByRole('button', { name: 'Open', exact: true }).click()
  check('directory locates original ID and expands target', await page.locator('[data-comment-id="1"]').getByRole('button', { name: 'Collapse', exact: true }).count() === 1)
  check('directory does not select located comment', await page.locator('[data-comment-id="1"]').getByRole('button', { name: /Select comment/ }).getAttribute('aria-pressed') === 'false')
  check('located target receives focus', await page.evaluate(() => document.activeElement?.getAttribute('data-comment-id') === '1'))
  for (const size of [{ width: 1200, height: 900 }, { width: 390, height: 800 }, { width: 640, height: 400 }]) {
    await page.setViewportSize(size)
    await page.getByRole('textbox', { name: 'Add a comment…' }).fill('Draft\n'.repeat(20))
    await page.evaluate(() => document.querySelectorAll('[data-kanban-scroller]').forEach(element => element.scrollTop = element.scrollHeight))
    const geometry = await page.evaluate(() => {
      const composer = document.querySelector('.kanban-composer').getBoundingClientRect()
      const columns = document.querySelector('.kanban-detail-columns').getBoundingClientRect()
      return { composerBottom: composer.bottom, composerTop: composer.top, columnsBottom: columns.bottom, columnsHeight: columns.height, overflow: document.documentElement.scrollWidth > innerWidth, inputs: document.querySelectorAll('textarea').length }
    })
    check(`single visible composer with readable scroller ${size.width}x${size.height}`, geometry.inputs === 1 && geometry.composerBottom <= size.height && geometry.columnsHeight > 32 && geometry.columnsBottom <= geometry.composerTop + 1 && !geometry.overflow)
    await page.screenshot({ path: root + `implementation-${size.width}x${size.height}.png` })
  }
  await page.setViewportSize({ width: 1200, height: 900 })
  await page.getByRole('textbox', { name: 'Add a comment…' }).fill('')
  await page.getByRole('button', { name: 'Open notes.md', exact: true }).click()
  await page.getByText('Original authenticated backend content.', { exact: false }).waitFor()
  check('filename reads real authenticated markdown without saving', await page.evaluate(() => window.saves.length === 0))
  const beforeRefresh = await page.evaluate(() => window.requests.filter(request => request.path.startsWith('/api/fs/read-text')).length)
  await page.evaluate(() => window.fixture.refresh())
  await page.waitForLoadState('networkidle')
  check('same-source task refresh does not restart an open material reader', await page.evaluate(() => window.requests.filter(request => request.path.startsWith('/api/fs/read-text')).length) === beforeRefresh)
  await page.getByRole('dialog').last().getByRole('button', { name: 'Close', exact: true }).click()
  await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Open notes.md', null, { timeout: 2000 })
  check('closing material restores focus to its original entry', await page.getByRole('button', { name: 'Open notes.md', exact: true }).evaluate(element => element === document.activeElement))
  await page.getByRole('button', { name: 'Open unsafe.html', exact: true }).click()
  const iframe = page.locator('iframe')
  await iframe.waitFor()
  await page.frameLocator('iframe').getByText('Safe HTML material').waitFor()
  check('HTML sandbox has no permissions', await iframe.getAttribute('sandbox') === '')
  check('HTML sanitization removes active and outgoing links', await page.frameLocator('iframe').locator('script,[href]').count() === 0)
  check('HTML made no external request', external.length === 0)
  await page.getByRole('dialog').last().getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('button', { name: 'Open real.pdf', exact: true }).click()
  await page.locator('iframe[title="real.pdf"]').waitFor({ timeout: 20000 })
  check('authenticated PDF bytes reach the native blob iframe', await page.locator('iframe[title="real.pdf"]').evaluate(async element => { const response = await fetch(element.src); return response.headers.get('content-type') === 'application/pdf' && (await response.text()).startsWith('%PDF-1.4') }))
  await page.screenshot({ path: root + 'implementation-pdf.png' })
  await page.getByRole('dialog').last().getByRole('button', { name: 'Close', exact: true }).click()
  const image = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aY9sAAAAASUVORK5CYII=', 'base64')
  const filename = `integration-${Date.now()}.png`, body = `Isolated real API image comment ${filename}`
  await page.locator('.kanban-composer input[type=file]').setInputFiles({ name: filename, mimeType: 'image/png', buffer: image })
  await page.getByRole('textbox', { name: 'Add a comment…' }).fill(body)
  await page.getByRole('button', { name: 'Comment', exact: true }).click()
  const saved = page.locator('[data-comment-id]').filter({ hasText: body })
  await saved.waitFor()
  await saved.locator(`img[alt="${filename}"]`).waitFor()
  check('uploaded image reference decodes in its newly saved ordinary comment', await saved.locator(`img[alt="${filename}"]`).evaluate(element => element.src.startsWith('data:image/') && element.complete && element.naturalWidth === 1))
  check('successful comment clears draft and pending image', await page.getByRole('textbox', { name: 'Add a comment…' }).inputValue() === '' && await page.locator('.kanban-composer img').count() === 0)
  check('all material reads carry original explicit owner', await page.evaluate(() => window.requests.filter(request => request.path.startsWith('/api/fs/')).every(request => request.connectionId === 'local')))
  check('no renderer script errors', errors.length === 0)
} finally {
  await writeFile(root + 'implementation-results.json', JSON.stringify({ fixture: 'Actual native components with real isolated Kanban/files HTTP routers and canonical session-token middleware; Electron IPC save cancellation is simulated; not installed product', checks, errors, external }, null, 2))
  await page.screenshot({ path: root + 'implementation-last.png' })
  await browser.close()
}
console.log(JSON.stringify({ passed: checks.length, checks, errors }))
