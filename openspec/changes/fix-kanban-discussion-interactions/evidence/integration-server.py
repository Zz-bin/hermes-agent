"""Isolated real Kanban/files HTTP fixture; never connects a production board."""
import argparse
import importlib.util
import json
import os
from pathlib import Path
import sys

parser = argparse.ArgumentParser()
parser.add_argument('--root', required=True)
parser.add_argument('--port', required=True, type=int)
args = parser.parse_args()
root = Path(args.root).resolve()
assert root.is_relative_to(Path(os.environ['TMPDIR']).resolve())
assert not root.exists(), 'Use a fresh fixture root'
root.mkdir(parents=True)
for key in list(os.environ):
    if key.startswith('HERMES_KANBAN_'):
        os.environ.pop(key)
os.environ.update(HOME=str(root / 'user'), HERMES_HOME=str(root / 'user' / '.hermes'), HERMES_KANBAN_HOME=str(root / 'board'), HERMES_KANBAN_DB=str(root / 'board' / 'kanban.db'))
# These marker-only profiles have no provider, credentials, or worker processes.
for name in ('builder', 'reviewer'):
    profile = root / 'user' / '.hermes' / 'profiles' / name
    profile.mkdir(parents=True)
    (profile / 'profile.yaml').write_text(f'name: {name}\n')
from hermes_cli import kanban_db as kb, kanban_db_connect as kbc
assert kb.kanban_home().resolve() == root / 'board'
assert kb.kanban_db_path().resolve() == root / 'board' / 'kanban.db'
kb.init_db()
with kbc.connect() as conn:
    task_id = kb.create_task(conn, title='Isolated native interaction fixture', body='Real isolated API data. No production task is touched.', assignee='builder', initial_status='blocked')
    for index in range(8):
        kb.add_comment(conn, task_id, 'builder' if index % 2 == 0 else 'reviewer', f'Floor {index + 1}\n\n' + '\n\n'.join(f'Paragraph {n}: isolated discussion reading content [link](https://example.invalid/).' for n in range(14)))
    directory = kb.task_attachments_dir(task_id)
    directory.mkdir(parents=True)
    materials = {
        'notes.md': ('text/markdown', b'# Isolated material\n\nOriginal authenticated backend content.'),
        'unsafe.html': ('text/html', b'<h1>Safe HTML material</h1><script>window.parent.postMessage("unsafe-executed","*")</script><img src="https://example.invalid/leak"><a href="https://example.invalid">blocked link</a>'),
        'unknown.bin': ('application/octet-stream', bytes(range(256))),
        'oversized.txt': ('text/plain', b'x' * (600 * 1024)),
    }
    # Valid minimal PDF, with generated byte offsets and cross-reference table.
    objects = [b'<< /Type /Catalog /Pages 2 0 R >>', b'<< /Type /Pages /Kids [3 0 R] /Count 1 >>', b'<< /Type /Page /Parent 2 0 R /MediaBox [0 0 200 200] /Contents 4 0 R >>', b'<< /Length 0 >>\nstream\n\nendstream']
    pdf = bytearray(b'%PDF-1.4\n')
    offsets = [0]
    for index, obj in enumerate(objects, 1):
        offsets.append(len(pdf))
        pdf.extend(f'{index} 0 obj\n'.encode() + obj + b'\nendobj\n')
    xref = len(pdf)
    pdf.extend(f'xref\n0 {len(offsets)}\n0000000000 65535 f \n'.encode())
    for offset in offsets[1:]:
        pdf.extend(f'{offset:010d} 00000 n \n'.encode())
    pdf.extend(f'trailer\n<< /Size {len(offsets)} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n'.encode())
    materials['real.pdf'] = ('application/pdf', bytes(pdf))
    for filename, (mime, data) in materials.items():
        path = directory / filename
        path.write_bytes(data)
        kb.add_attachment(conn, task_id, filename=filename, stored_path=str(path), content_type=mime, size=len(data), uploaded_by='isolated-fixture')

    for filename in ('missing.txt', 'denied.txt'):
        path = directory / filename
        if filename == 'denied.txt':
            path.write_text('isolated unreadable material')
            path.chmod(0)
        kb.add_attachment(conn, task_id, filename=filename, stored_path=str(path), content_type='text/plain', size=28, uploaded_by='isolated-fixture')


from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from hermes_cli.web_routers.files import router as files_router
from hermes_cli import web_server
import uvicorn
spec = importlib.util.spec_from_file_location('isolated_kanban_api', Path(__file__).resolve().parents[4] / 'plugins' / 'kanban' / 'dashboard' / 'plugin_api.py')
assert spec is not None and spec.loader is not None
module = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = module
spec.loader.exec_module(module)
app = FastAPI()
# Canonical token authentication, no real user token or OAuth state.
web_server._apply_ssh_session_token('isolated-fixture-only')
app.middleware('http')(web_server.auth_middleware)
app.add_middleware(CORSMiddleware, allow_origins=['http://127.0.0.1:43311'], allow_methods=['*'], allow_headers=['*'])
app.include_router(module.router, prefix='/api/plugins/kanban')
app.include_router(files_router)
audit = []
@app.middleware('http')
async def record_source(request, call_next):
    if request.url.path.startswith('/api/'):
        audit.append({'path': request.url.path, 'profile': request.query_params.get('profile'), 'method': request.method})
    return await call_next(request)
@app.get('/fixture-audit')
def fixture_audit():
    return audit
@app.get('/fixture-info')
def info():
    return {'task_id': task_id, 'root': str(root), 'fixture': 'real isolated DB, native routers, canonical token middleware; not full serve/Electron'}
(root / 'fixture.json').write_text(json.dumps(info(), indent=2))
uvicorn.run(app, host='127.0.0.1', port=args.port, log_level='warning', access_log=False)
